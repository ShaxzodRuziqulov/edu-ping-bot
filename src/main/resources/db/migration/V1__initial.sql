CREATE TABLE app_user (
  id bigint PRIMARY KEY, display_name varchar(200) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE classroom (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id bigint NOT NULL REFERENCES app_user(id), name varchar(80) NOT NULL,
  invite_code varchar(32) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(), UNIQUE (teacher_id, name)
);
CREATE TABLE membership (
  classroom_id bigint REFERENCES classroom(id), student_id bigint REFERENCES app_user(id),
  joined_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY (classroom_id, student_id)
);
CREATE TABLE ticket (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classroom_id bigint NOT NULL REFERENCES classroom(id), student_id bigint NOT NULL REFERENCES app_user(id),
  subject varchar(120) NOT NULL, status varchar(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
  created_at timestamptz NOT NULL DEFAULT now(), closed_at timestamptz
);
CREATE INDEX ticket_student ON ticket(student_id, id DESC);
CREATE INDEX ticket_class_status ON ticket(classroom_id, status, id DESC);
CREATE TABLE chat_session (
  user_id bigint PRIMARY KEY REFERENCES app_user(id), ticket_id bigint NOT NULL REFERENCES ticket(id)
);
CREATE TABLE ticket_message (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES ticket(id), sender_id bigint NOT NULL REFERENCES app_user(id),
  kind varchar(20) NOT NULL, body text NOT NULL DEFAULT '', file_id text, file_unique_id text,
  file_name varchar(255), mime_type varchar(150), file_size bigint,
  archive_state varchar(12) NOT NULL DEFAULT 'NONE' CHECK (archive_state IN ('NONE','PENDING','STORED','FAILED')),
  file_bytes bytea, sha256 varchar(64), created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (octet_length(file_bytes) <= 20971520)
);
CREATE INDEX message_ticket ON ticket_message(ticket_id, id);
CREATE TABLE inbox (
  update_id bigint PRIMARY KEY, payload text NOT NULL,
  state varchar(12) NOT NULL DEFAULT 'PENDING', attempts integer NOT NULL DEFAULT 0,
  available_at timestamptz NOT NULL DEFAULT now(), error_code varchar(80),
  created_at timestamptz NOT NULL DEFAULT now(), processed_at timestamptz
);
CREATE INDEX inbox_pending ON inbox(available_at, update_id) WHERE state = 'PENDING';
CREATE TABLE outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_type varchar(12) NOT NULL CHECK (job_type IN ('API','ARCHIVE')),
  chat_id bigint, method varchar(30), payload text, message_id bigint REFERENCES ticket_message(id),
  state varchar(12) NOT NULL DEFAULT 'PENDING', attempts integer NOT NULL DEFAULT 0,
  available_at timestamptz NOT NULL DEFAULT now(), error_code varchar(80),
  created_at timestamptz NOT NULL DEFAULT now(), sent_at timestamptz
);
CREATE INDEX outbox_pending ON outbox(available_at, id) WHERE state = 'PENDING';
CREATE TABLE delivery_clock (chat_id bigint PRIMARY KEY, sent_at timestamptz NOT NULL);
CREATE TABLE join_attempt (user_id bigint NOT NULL REFERENCES app_user(id), created_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX join_attempt_user ON join_attempt(user_id, created_at);
CREATE TABLE audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id bigint NOT NULL,
  action varchar(40) NOT NULL, entity_id bigint, created_at timestamptz NOT NULL DEFAULT now()
);
